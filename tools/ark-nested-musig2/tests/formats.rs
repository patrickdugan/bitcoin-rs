use std::str::FromStr as _;

use bitcoin::hex::DisplayHex as _;
use bitcoin::secp256k1::XOnlyPublicKey;
use bitcoin_rs_ark_nested_musig2::scripts::{VtxoScript, nums_compressed};
use serde::Deserialize;

use super::support::TestError;

#[derive(Deserialize)]
struct Fixture {
    ark_core_rev: String,
    cases: Vec<Case>,
}

#[derive(Deserialize)]
struct Case {
    server_xonly: String,
    owner_xonly: String,
    exit_blocks: u16,
    script_pubkey: String,
    tapscripts: Vec<String>,
}

// Independent oracle: arkade-os/rust-sdk ark-core `Vtxo::new_default` at the
// pinned revision, generated by tools/ark-nested-musig2/interop.
#[test]
fn default_vtxo_matches_arkade_rust_sdk() -> Result<(), TestError> {
    let fixture: Fixture = sonic_rs::from_str(include_str!("../interop/fixtures/g-2g-12.json"))?;
    assert_eq!(
        fixture.ark_core_rev,
        "c786942969dd16f9e94fc165a99a329a39ed183d"
    );
    for case in fixture.cases {
        let script = VtxoScript {
            owner: XOnlyPublicKey::from_str(&case.owner_xonly)?,
            asp: XOnlyPublicKey::from_str(&case.server_xonly)?,
            exit_delay: case.exit_blocks,
        };
        assert_eq!(script.script_pubkey()?.to_hex_string(), case.script_pubkey);
        let mut ours = vec![
            script.cooperative_leaf().to_hex_string(),
            script.exit_leaf().to_hex_string(),
        ];
        let mut theirs = case.tapscripts.clone();
        ours.sort();
        theirs.sort();
        assert_eq!(ours, theirs);
    }
    Ok(())
}

// BIP341 names H = lift_x(0x50929b74...803ac0) as the unspendable internal key.
#[test]
fn unspendable_internal_key_is_bip341_h() {
    assert_eq!(
        nums_compressed().to_lower_hex_string(),
        "0250929b74c1a04954b78b4b6035e97a5e078a5a0f28ec96d547bfee9ace803ac0"
    );
}
